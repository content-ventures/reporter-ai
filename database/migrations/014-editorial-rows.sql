-- Editorial state as rows instead of one JSONB document per portal. Safe to replay.
-- A command reads only the rows it needs and writes only the rows it changed; every
-- synced write is stamped with a per-portal change counter so browsers fetch deltas.
BEGIN;

CREATE TABLE IF NOT EXISTS public.reporter_ed_sync(
  portal_id uuid PRIMARY KEY REFERENCES public.portals(id),
  seq bigint NOT NULL DEFAULT 0 CHECK(seq>=0),
  floor_seq bigint NOT NULL DEFAULT 0 CHECK(floor_seq>=0),
  migrated_at timestamptz
);
CREATE TABLE IF NOT EXISTS public.reporter_ed_workspace(
  portal_id uuid PRIMARY KEY REFERENCES public.portals(id),
  doc jsonb NOT NULL CHECK(jsonb_typeof(doc)='object' AND octet_length(doc::text)<=1048576),
  seq bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS public.reporter_ed_productions(
  portal_id uuid NOT NULL REFERENCES public.portals(id),
  production_id text NOT NULL CHECK(length(production_id) BETWEEN 1 AND 128),
  ordinal bigint GENERATED BY DEFAULT AS IDENTITY,
  doc jsonb NOT NULL CHECK(jsonb_typeof(doc)='object' AND octet_length(doc::text)<=1048576),
  source_ids text[] NOT NULL DEFAULT '{}',
  archived boolean NOT NULL DEFAULT false,
  seq bigint NOT NULL,
  PRIMARY KEY(portal_id,production_id)
);
CREATE INDEX IF NOT EXISTS reporter_ed_productions_sources_idx ON public.reporter_ed_productions USING gin(source_ids);
CREATE TABLE IF NOT EXISTS public.reporter_ed_parts(
  portal_id uuid NOT NULL REFERENCES public.portals(id),
  kind text NOT NULL CHECK(kind IN ('piece','version','decision','review','run','suggestion','delivery')),
  part_id text NOT NULL CHECK(length(part_id) BETWEEN 1 AND 128),
  production_id text NOT NULL,
  ordinal bigint GENERATED BY DEFAULT AS IDENTITY,
  doc jsonb CHECK(doc IS NULL OR octet_length(doc::text)<=4194304),
  deleted boolean NOT NULL DEFAULT false,
  seq bigint NOT NULL,
  PRIMARY KEY(portal_id,kind,part_id),
  FOREIGN KEY(portal_id,production_id) REFERENCES public.reporter_ed_productions(portal_id,production_id)
);
CREATE INDEX IF NOT EXISTS reporter_ed_parts_entity_idx ON public.reporter_ed_parts(portal_id,part_id);
CREATE INDEX IF NOT EXISTS reporter_ed_parts_production_idx ON public.reporter_ed_parts(portal_id,production_id);
CREATE TABLE IF NOT EXISTS public.reporter_ed_sources(
  portal_id uuid NOT NULL REFERENCES public.portals(id),
  source_id text NOT NULL CHECK(length(source_id) BETWEEN 1 AND 128),
  ordinal bigint GENERATED BY DEFAULT AS IDENTITY,
  doc jsonb NOT NULL CHECK(jsonb_typeof(doc)='object' AND octet_length(doc::text)<=4194304),
  seq bigint NOT NULL,
  PRIMARY KEY(portal_id,source_id)
);
CREATE TABLE IF NOT EXISTS public.reporter_ed_runs(
  portal_id uuid NOT NULL REFERENCES public.portals(id),
  run_id text NOT NULL CHECK(length(run_id) BETWEEN 1 AND 128),
  production_id text NOT NULL,
  status text NOT NULL,
  available_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  lease_owner text, lease_until timestamptz, lease_fence text,
  attempts integer NOT NULL DEFAULT 0 CHECK(attempts>=0),
  job jsonb CHECK(job IS NULL OR octet_length(job::text)<=4194304),
  fold jsonb NOT NULL CHECK(octet_length(fold::text)<=4194304),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  finished_at timestamptz,
  seq bigint NOT NULL,
  PRIMARY KEY(portal_id,run_id),
  FOREIGN KEY(portal_id,production_id) REFERENCES public.reporter_ed_productions(portal_id,production_id),
  CHECK((lease_owner IS NULL)=(lease_until IS NULL))
);
CREATE INDEX IF NOT EXISTS reporter_ed_runs_claim_idx ON public.reporter_ed_runs(portal_id,available_at)
  WHERE status IN ('queued','running','awaiting_input') AND job IS NOT NULL;
CREATE TABLE IF NOT EXISTS public.reporter_ed_run_events(
  portal_id uuid NOT NULL,
  run_id text NOT NULL,
  event_seq integer NOT NULL CHECK(event_seq>0),
  event jsonb NOT NULL CHECK(octet_length(event::text)<=1048576),
  seq bigint NOT NULL,
  PRIMARY KEY(portal_id,run_id,event_seq),
  FOREIGN KEY(portal_id,run_id) REFERENCES public.reporter_ed_runs(portal_id,run_id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS public.reporter_ed_items(
  portal_id uuid NOT NULL REFERENCES public.portals(id),
  kind text NOT NULL CHECK(kind IN ('person','member','activity','feedback','image_asset','citation','library_image','banner')),
  item_id text NOT NULL CHECK(length(item_id) BETWEEN 1 AND 256),
  production_id text,
  ordinal bigint GENERATED BY DEFAULT AS IDENTITY,
  doc jsonb CHECK(doc IS NULL OR octet_length(doc::text)<=1048576),
  deleted boolean NOT NULL DEFAULT false,
  seq bigint NOT NULL,
  PRIMARY KEY(portal_id,kind,item_id)
);
CREATE INDEX IF NOT EXISTS reporter_ed_items_production_idx ON public.reporter_ed_items(portal_id,kind,production_id);
CREATE TABLE IF NOT EXISTS public.reporter_ed_receipts(
  portal_id uuid NOT NULL REFERENCES public.portals(id),
  request_id text NOT NULL CHECK(length(request_id) BETWEEN 1 AND 128),
  hash text NOT NULL,
  result jsonb CHECK(result IS NULL OR octet_length(result::text)<=4194304),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  PRIMARY KEY(portal_id,request_id)
);
CREATE TABLE IF NOT EXISTS public.reporter_ed_pipelines(
  portal_id uuid NOT NULL REFERENCES public.portals(id),
  hash text NOT NULL CHECK(length(hash) BETWEEN 1 AND 128),
  doc jsonb NOT NULL CHECK(octet_length(doc::text)<=4194304),
  PRIMARY KEY(portal_id,hash)
);

CREATE INDEX IF NOT EXISTS reporter_ed_productions_seq_idx ON public.reporter_ed_productions(portal_id,seq);
CREATE INDEX IF NOT EXISTS reporter_ed_parts_seq_idx ON public.reporter_ed_parts(portal_id,seq);
CREATE INDEX IF NOT EXISTS reporter_ed_sources_seq_idx ON public.reporter_ed_sources(portal_id,seq);
CREATE INDEX IF NOT EXISTS reporter_ed_runs_seq_idx ON public.reporter_ed_runs(portal_id,seq);
CREATE INDEX IF NOT EXISTS reporter_ed_run_events_seq_idx ON public.reporter_ed_run_events(portal_id,seq);
CREATE INDEX IF NOT EXISTS reporter_ed_items_seq_idx ON public.reporter_ed_items(portal_id,seq);

DO $$
DECLARE relation text;
BEGIN
  FOREACH relation IN ARRAY ARRAY['reporter_ed_sync','reporter_ed_workspace','reporter_ed_productions','reporter_ed_parts',
    'reporter_ed_sources','reporter_ed_runs','reporter_ed_run_events','reporter_ed_items','reporter_ed_receipts','reporter_ed_pipelines'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',relation);
    EXECUTE format('REVOKE ALL ON public.%I FROM PUBLIC',relation);
    EXECUTE format('GRANT SELECT,INSERT,UPDATE,DELETE ON public.%I TO reporter_executor',relation);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I',relation||'_executor',relation);
    EXECUTE format('CREATE POLICY %I ON public.%I TO reporter_executor USING(true) WITH CHECK(true)',relation||'_executor',relation);
  END LOOP;
END $$;

-- The session's portal: workers by job context, people by the permission the named command needs.
CREATE OR REPLACE FUNCTION core.reporter_ed_portal(p_write boolean) RETURNS uuid
LANGUAGE plpgsql SET search_path=pg_catalog,core,public,pg_temp AS $$
DECLARE portal uuid;
BEGIN
  IF current_setting('app.access_mode',true)='job' THEN
    PERFORM core.reporter_worker_require();
    portal := nullif(current_setting('app.portal_id',true),'')::uuid;
  ELSE
    portal := core.reporter_require(CASE WHEN NOT p_write THEN 'reporter.read'
      WHEN current_setting('app.editorial_permission',true)='reporter.review' THEN 'reporter.review' ELSE 'reporter.edit' END);
  END IF;
  IF portal IS NULL THEN RAISE EXCEPTION 'Portal context missing' USING ERRCODE='42501'; END IF;
  RETURN portal;
END $$;

-- Rows the command needs, in insertion order. Writers lock what they may change, in a fixed
-- order (workspace, productions by id, runs by id), so concurrent commands never deadlock.
CREATE OR REPLACE FUNCTION public.reporter_ed_load(p_scope jsonb) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,core,public,pg_temp AS $$
DECLARE
  write boolean := coalesce((p_scope->>'write')::boolean,false);
  portal uuid := core.reporter_ed_portal(write);
  everything boolean := p_scope->'productions'='"all"'::jsonb;
  ids text[]; kinds text[]; run_ids text[]; loaded jsonb;
BEGIN
  IF jsonb_typeof(p_scope) IS DISTINCT FROM 'object' OR octet_length(p_scope::text)>262144 THEN
    RAISE EXCEPTION 'Invalid editorial scope' USING ERRCODE='22023'; END IF;
  INSERT INTO public.reporter_ed_sync(portal_id) VALUES(portal) ON CONFLICT DO NOTHING;
  IF write AND coalesce((p_scope->>'workspace_lock')::boolean,false) THEN
    PERFORM 1 FROM public.reporter_ed_workspace WHERE portal_id=portal FOR UPDATE;
  END IF;
  -- Productions named directly, owning a named entity, or using a named source.
  SELECT array_agg(DISTINCT id ORDER BY id) INTO ids FROM (
    SELECT jsonb_array_elements_text(CASE WHEN jsonb_typeof(p_scope->'productions')='array' THEN p_scope->'productions' ELSE '[]' END) AS id
    UNION SELECT p.production_id FROM public.reporter_ed_parts p
      WHERE p.portal_id=portal AND p.part_id IN (SELECT jsonb_array_elements_text(coalesce(p_scope->'entities','[]')))
    UNION SELECT r.production_id FROM public.reporter_ed_runs r
      WHERE r.portal_id=portal AND r.run_id IN (SELECT jsonb_array_elements_text(coalesce(p_scope->'entities','[]')))
    UNION SELECT r.production_id FROM public.reporter_ed_productions r
      WHERE r.portal_id=portal AND r.source_ids && ARRAY(SELECT jsonb_array_elements_text(coalesce(p_scope->'source_users','[]')))
  ) wanted;
  IF everything THEN SELECT array_agg(production_id ORDER BY production_id) INTO ids FROM public.reporter_ed_productions WHERE portal_id=portal; END IF;
  ids := coalesce(ids,'{}');
  IF write THEN
    PERFORM 1 FROM public.reporter_ed_productions WHERE portal_id=portal AND production_id=ANY(ids) ORDER BY production_id FOR UPDATE;
  END IF;
  kinds := CASE WHEN jsonb_typeof(p_scope->'parts')='array' THEN ARRAY(SELECT jsonb_array_elements_text(p_scope->'parts'))
    ELSE ARRAY['piece','version','decision','review','run','suggestion','delivery'] END;
  SELECT array_agg(run_id ORDER BY run_id) INTO run_ids FROM public.reporter_ed_runs
    WHERE portal_id=portal AND (production_id=ANY(ids) OR run_id IN (SELECT jsonb_array_elements_text(coalesce(p_scope->'runs','[]'))));
  run_ids := coalesce(run_ids,'{}');
  IF write THEN PERFORM 1 FROM public.reporter_ed_runs WHERE portal_id=portal AND run_id=ANY(run_ids) ORDER BY run_id FOR UPDATE; END IF;
  SELECT jsonb_build_object(
    'seq',(SELECT seq FROM public.reporter_ed_sync WHERE portal_id=portal),
    'workspace',(SELECT doc FROM public.reporter_ed_workspace WHERE portal_id=portal),
    'productions',coalesce((SELECT jsonb_agg(jsonb_build_object('id',production_id,'ordinal',ordinal,'doc',doc,
      'sourceIds',to_jsonb(source_ids),'archived',archived) ORDER BY ordinal) FROM public.reporter_ed_productions
      WHERE portal_id=portal AND production_id=ANY(ids)),'[]'),
    'parts',coalesce((SELECT jsonb_agg(jsonb_build_object('kind',kind,'id',part_id,'productionId',production_id,'ordinal',ordinal,'doc',doc) ORDER BY ordinal)
      FROM public.reporter_ed_parts WHERE portal_id=portal AND production_id=ANY(ids) AND kind=ANY(kinds) AND NOT deleted),'[]'),
    'sources',coalesce((SELECT jsonb_agg(jsonb_build_object('id',source_id,'ordinal',ordinal,'doc',doc) ORDER BY ordinal)
      FROM public.reporter_ed_sources s WHERE s.portal_id=portal AND (p_scope->'sources'='"all"'::jsonb
        OR s.source_id IN (SELECT unnest(source_ids) FROM public.reporter_ed_productions WHERE portal_id=portal AND production_id=ANY(ids))
        OR s.source_id IN (SELECT jsonb_array_elements_text(CASE WHEN jsonb_typeof(p_scope->'sources')='array' THEN p_scope->'sources' ELSE '[]' END)))),'[]'),
    'runs',coalesce((SELECT jsonb_agg(jsonb_build_object('id',run_id,'productionId',production_id,'status',status,
      'availableAt',(extract(epoch FROM available_at)*1000)::bigint,'lease',CASE WHEN lease_owner IS NULL THEN NULL ELSE jsonb_build_object(
        'owner',lease_owner,'until',(extract(epoch FROM lease_until)*1000)::bigint,'fence',lease_fence) END,
      'attempts',attempts,'job',CASE WHEN coalesce((p_scope->>'jobs')::boolean,true) THEN job END,'fold',fold) ORDER BY created_at,run_id)
      FROM public.reporter_ed_runs WHERE portal_id=portal AND run_id=ANY(run_ids)),'[]'),
    'events',coalesce((SELECT jsonb_agg(jsonb_build_object('runId',e.run_id,'event',e.event) ORDER BY e.run_id,e.event_seq)
      FROM public.reporter_ed_run_events e JOIN public.reporter_ed_runs r ON (r.portal_id,r.run_id)=(e.portal_id,e.run_id)
      WHERE e.portal_id=portal AND e.run_id=ANY(run_ids) AND (
        p_scope->'events'='"active"'::jsonb AND r.status IN ('queued','running','awaiting_input')
        OR e.run_id IN (SELECT jsonb_array_elements_text(CASE WHEN jsonb_typeof(p_scope->'events')='array' THEN p_scope->'events' ELSE '[]' END)))),'[]'),
    'items',coalesce((SELECT jsonb_agg(jsonb_build_object('kind',i.kind,'id',i.item_id,'productionId',i.production_id,'ordinal',i.ordinal,'doc',i.doc) ORDER BY i.ordinal)
      FROM public.reporter_ed_items i WHERE i.portal_id=portal AND NOT i.deleted AND (
        p_scope->'items'->i.kind='"all"'::jsonb
        OR p_scope->'items'->i.kind='"production"'::jsonb AND (i.production_id IS NULL OR i.production_id=ANY(ids))
        OR i.item_id IN (SELECT jsonb_array_elements_text(CASE WHEN jsonb_typeof(p_scope->'items'->i.kind)='array' THEN p_scope->'items'->i.kind ELSE '[]' END)))),'[]'),
    'pipelines',coalesce((SELECT jsonb_agg(jsonb_build_object('hash',hash,'doc',doc)) FROM public.reporter_ed_pipelines
      WHERE portal_id=portal AND hash IN (SELECT jsonb_array_elements_text(coalesce(p_scope->'pipelines','[]'))
        UNION SELECT doc->>'pipelineHash' FROM public.reporter_ed_workspace WHERE portal_id=portal
        UNION SELECT jsonb_array_elements_text(coalesce(doc->'historyHashes','[]')) FROM public.reporter_ed_workspace
          WHERE portal_id=portal AND coalesce((p_scope->>'history')::boolean,false)
        UNION SELECT job->>'pipelineHash' FROM public.reporter_ed_runs WHERE portal_id=portal AND run_id=ANY(run_ids)
          AND coalesce((p_scope->>'jobs')::boolean,true))),'[]'),
    'receipt',(SELECT jsonb_build_object('hash',r.hash,'result',r.result) FROM public.reporter_ed_receipts r
      WHERE r.portal_id=portal AND r.request_id=p_scope->>'receipt')
  ) INTO loaded;
  RETURN loaded;
END $$;

-- Applies one command's changed rows, stamped with the next change number. It is the last
-- call of the transaction, so the counter lock is held only for these writes and commits are
-- numbered in commit order: a reader that has seen number N has seen every row stamped N or lower.
CREATE OR REPLACE FUNCTION public.reporter_ed_commit(p_changes jsonb) RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,core,public,pg_temp AS $$
DECLARE portal uuid := core.reporter_ed_portal(true); next_seq bigint; entry jsonb;
BEGIN
  IF jsonb_typeof(p_changes) IS DISTINCT FROM 'object' OR octet_length(p_changes::text)>33554432 THEN
    RAISE EXCEPTION 'Invalid editorial changes' USING ERRCODE='22023'; END IF;
  INSERT INTO public.reporter_ed_sync(portal_id) VALUES(portal) ON CONFLICT DO NOTHING;
  IF p_changes ? 'receipt' THEN
    INSERT INTO public.reporter_ed_receipts(portal_id,request_id,hash,result)
      VALUES(portal,p_changes->'receipt'->>'requestId',p_changes->'receipt'->>'hash',p_changes->'receipt'->'result')
      ON CONFLICT(portal_id,request_id) DO NOTHING;
    IF NOT FOUND THEN RAISE EXCEPTION 'Command already recorded' USING ERRCODE='40001'; END IF;
  END IF;
  UPDATE public.reporter_ed_sync SET seq=seq+1 WHERE portal_id=portal RETURNING seq INTO next_seq;
  IF p_changes ? 'workspace' THEN
    INSERT INTO public.reporter_ed_workspace(portal_id,doc,seq) VALUES(portal,p_changes->'workspace',next_seq)
      ON CONFLICT(portal_id) DO UPDATE SET doc=excluded.doc,seq=next_seq;
  END IF;
  FOR entry IN SELECT * FROM jsonb_array_elements(coalesce(p_changes->'productions','[]')) LOOP
    INSERT INTO public.reporter_ed_productions(portal_id,production_id,doc,source_ids,archived,seq)
      VALUES(portal,entry->>'id',entry->'doc',ARRAY(SELECT jsonb_array_elements_text(coalesce(entry->'sourceIds','[]'))),
        coalesce((entry->>'archived')::boolean,false),next_seq)
      ON CONFLICT(portal_id,production_id) DO UPDATE SET doc=excluded.doc,source_ids=excluded.source_ids,archived=excluded.archived,seq=next_seq;
  END LOOP;
  FOR entry IN SELECT * FROM jsonb_array_elements(coalesce(p_changes->'sources','[]')) LOOP
    INSERT INTO public.reporter_ed_sources(portal_id,source_id,doc,seq) VALUES(portal,entry->>'id',entry->'doc',next_seq)
      ON CONFLICT(portal_id,source_id) DO UPDATE SET doc=excluded.doc,seq=next_seq;
  END LOOP;
  FOR entry IN SELECT * FROM jsonb_array_elements(coalesce(p_changes->'parts','[]')) LOOP
    INSERT INTO public.reporter_ed_parts(portal_id,kind,part_id,production_id,doc,deleted,seq)
      VALUES(portal,entry->>'kind',entry->>'id',entry->>'productionId',entry->'doc',coalesce((entry->>'deleted')::boolean,false),next_seq)
      ON CONFLICT(portal_id,kind,part_id) DO UPDATE SET doc=excluded.doc,deleted=excluded.deleted,seq=next_seq
        WHERE reporter_ed_parts.production_id=excluded.production_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Part belongs to another production' USING ERRCODE='22023'; END IF;
  END LOOP;
  FOR entry IN SELECT * FROM jsonb_array_elements(coalesce(p_changes->'runs','[]')) LOOP
    INSERT INTO public.reporter_ed_runs(portal_id,run_id,production_id,status,available_at,lease_owner,lease_until,lease_fence,
        attempts,job,fold,finished_at,seq)
      VALUES(portal,entry->>'id',entry->>'productionId',entry->>'status',
        to_timestamp(coalesce((entry->>'availableAt')::numeric,extract(epoch FROM clock_timestamp())*1000)/1000),
        entry->'lease'->>'owner',to_timestamp((entry->'lease'->>'until')::numeric/1000),entry->'lease'->>'fence',
        coalesce((entry->>'attempts')::int,0),entry->'job',entry->'fold',
        CASE WHEN entry->>'status' IN ('completed','failed','cancelled') THEN clock_timestamp() END,next_seq)
      ON CONFLICT(portal_id,run_id) DO UPDATE SET status=excluded.status,available_at=excluded.available_at,
        lease_owner=excluded.lease_owner,lease_until=excluded.lease_until,lease_fence=excluded.lease_fence,
        attempts=excluded.attempts,job=excluded.job,fold=excluded.fold,
        finished_at=coalesce(reporter_ed_runs.finished_at,excluded.finished_at),seq=next_seq
        WHERE reporter_ed_runs.production_id=excluded.production_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Run belongs to another production' USING ERRCODE='22023'; END IF;
  END LOOP;
  FOR entry IN SELECT * FROM jsonb_array_elements(coalesce(p_changes->'events','[]')) LOOP
    INSERT INTO public.reporter_ed_run_events(portal_id,run_id,event_seq,event,seq)
      VALUES(portal,entry->>'runId',(entry->'event'->>'seq')::int,entry->'event',next_seq)
      ON CONFLICT(portal_id,run_id,event_seq) DO UPDATE SET event=excluded.event,seq=next_seq;
  END LOOP;
  FOR entry IN SELECT * FROM jsonb_array_elements(coalesce(p_changes->'items','[]')) LOOP
    INSERT INTO public.reporter_ed_items(portal_id,kind,item_id,production_id,doc,deleted,seq)
      VALUES(portal,entry->>'kind',entry->>'id',entry->>'productionId',entry->'doc',coalesce((entry->>'deleted')::boolean,false),next_seq)
      ON CONFLICT(portal_id,kind,item_id) DO UPDATE SET production_id=excluded.production_id,doc=excluded.doc,deleted=excluded.deleted,seq=next_seq;
  END LOOP;
  FOR entry IN SELECT * FROM jsonb_array_elements(coalesce(p_changes->'pipelines','[]')) LOOP
    INSERT INTO public.reporter_ed_pipelines(portal_id,hash,doc) VALUES(portal,entry->>'hash',entry->'doc') ON CONFLICT DO NOTHING;
  END LOOP;
  RETURN next_seq;
END $$;

ALTER FUNCTION core.reporter_ed_portal(boolean) OWNER TO reporter_executor;
ALTER FUNCTION public.reporter_ed_load(jsonb) OWNER TO reporter_executor;
ALTER FUNCTION public.reporter_ed_commit(jsonb) OWNER TO reporter_executor;
REVOKE ALL ON FUNCTION core.reporter_ed_portal(boolean),public.reporter_ed_load(jsonb),public.reporter_ed_commit(jsonb) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.reporter_ed_load(jsonb),public.reporter_ed_commit(jsonb) TO reporter_runtime,reporter_worker;
COMMIT;
